package br.com.territorio.persistencia;

import java.sql.*;
public class BancoDados {
    private final String url;
    public BancoDados(String url) { this.url = url; }
    public Connection abrirConexao() throws SQLException { return DriverManager.getConnection(url, "sa", ""); }
    public void inicializar() throws SQLException {
        try (Connection c = abrirConexao(); Statement s = c.createStatement()) {
            s.execute("""
                CREATE TABLE IF NOT EXISTS medicao (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  sensor_id VARCHAR(100) NOT NULL, tipo VARCHAR(30) NOT NULL,
                  valor DOUBLE PRECISION NOT NULL CHECK (valor >= 0), instante TIMESTAMP NOT NULL)
                """);
            s.execute("CREATE INDEX IF NOT EXISTS idx_medicao_sensor ON medicao(sensor_id, instante, id)");
            s.execute("""
                CREATE TABLE IF NOT EXISTS alerta (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  sensor_id VARCHAR(100) NOT NULL, tipo VARCHAR(30) NOT NULL, nivel VARCHAR(20) NOT NULL,
                  valor_previsto DOUBLE PRECISION NOT NULL, limite DOUBLE PRECISION NOT NULL,
                  estrategia VARCHAR(100) NOT NULL, mensagem VARCHAR(1000) NOT NULL, instante TIMESTAMP NOT NULL)
                """);
        }
    }
}
